first_number = int(input("Enter the first number: "))
second_number = int(input("Enter the second number: "))

sum_result = int(first_number) + int(second_number)
subtraction_result = int(first_number) - int(second_number)
multiplication_result = int(first_number) * int(second_number)
division_result = int(first_number) / int(second_number)

print(f"The sum is {sum_result}")
print(f"The subtraction is {subtraction_result}")
print(f"The multiplication is {multiplication_result}")
print(f"The division is {division_result}")
